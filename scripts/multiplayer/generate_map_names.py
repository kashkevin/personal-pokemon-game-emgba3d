"""Generate src/emerald_multiplayer/map_names.py: the place name of every map (towns, buildings, caves included).

Map group and number follow the engine's data/maps/map_groups.json (the game's MAP_GROUP / MAP_NUM); the name is the
map's region map section name (src/data/region_map/region_map_sections.json), the name the game itself shows. The
shared spawn catalogue only names maps with wild Pokemon, so towns and buildings showed as "Area 0-9" in PLAYERS and
PokeNav (docs/multiplayer-session-fix-20261019.md).

    python scripts/multiplayer/generate_map_names.py --engine ../engine
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[2] / "src" / "emerald_multiplayer" / "map_names.py"
UNNAMED = {"MAPSEC_NONE", "MAPSEC_DYNAMIC"}


def names(engine: Path) -> dict[str, str]:
    groups = json.loads((engine / "data/maps/map_groups.json").read_text())
    sections = {s["id"]: s["name"] for s in
                json.loads((engine / "src/data/region_map/region_map_sections.json").read_text())["map_sections"]
                if s.get("name")}
    table = {}
    for group, key in enumerate(groups["group_order"]):
        for number, folder in enumerate(groups[key]):
            section = json.loads((engine / "data/maps" / folder / "map.json").read_text()).get("region_map_section")
            if section not in UNNAMED and section in sections:
                table[f"{group}.{number}"] = sections[section]
    return table


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--engine", type=Path, required=True)
    args = parser.parse_args()
    table = names(args.engine.resolve())
    data = json.dumps(table, sort_keys=True, separators=(",", ":"))
    lines = [data[i:i + 100] for i in range(0, len(data), 100)]
    OUTPUT.write_text(
        '"""Place names of every map, generated by scripts/multiplayer/generate_map_names.py from the pinned engine.\n\n'
        'Key "group.number" (the game\'s map group and number); value the map\'s region map section name, as the game\n'
        'shows it. Do not edit by hand; re-run the generator.\n"""\n'
        "import json\n\n"
        f"MAP_NAMES_SHA256 = {hashlib.sha256(data.encode()).hexdigest()!r}\n"
        "MAP_NAMES = json.loads(\n" + "\n".join(f"    {line!r}" for line in lines) + ")\n")
    print(f"{len(table)} maps -> {OUTPUT}")


if __name__ == "__main__":
    main()
